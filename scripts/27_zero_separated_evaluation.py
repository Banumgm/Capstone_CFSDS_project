"""
Phase 4, Step 3 — Zero-Separated & Extreme Event Evaluation
27_zero_separated_evaluation.py

Evaluates the continuous regression model across isolated subsets of the test data:
zero-spread days, active-spread days, and extreme high-spread events. This directly
addresses operational audit requirements to ensure baseline metrics do not mask
model performance during catastrophic wildfire scenarios.
"""
import pandas as pd
import numpy as np
import joblib
from sklearn.metrics import mean_squared_error, mean_absolute_error

# 1. Setup local paths
BASE_DIR = "processed"
MODEL_DIR = "models"

# 2. Load the data and model (required for standalone script)
print("Loading regression model and test data...")
X_test = pd.read_csv(f"{BASE_DIR}/X_test_tree.csv")
X_test["ecozone"] = X_test["ecozone"].astype("category")

# Use y_test.csv (removed _tree suffix to match downloaded files)
y_test_reg = pd.read_csv(f"{BASE_DIR}/y_test.csv").squeeze() 

# Load the regression model generated by script 25
final_lgb_reg = joblib.load(f"{MODEL_DIR}/lgbm_regressor.pkl") 

# 3. Execute original evaluation logic
print("Generating predictions on the test set using fitted Regressor...")
y_pred_reg = final_lgb_reg.predict(X_test)

eval_df_reg = pd.DataFrame({
    "y_true": y_test_reg,
    "y_pred": y_pred_reg
})

PERCENTILE_90_THRESHOLD = 984.44

subsets = {
    "1. Global (All Test Data)": eval_df_reg,
    "2. Zero-Spread Days (y = 0)": eval_df_reg[eval_df_reg["y_true"] == 0],
    "3. Active-Spread Days (y > 0)": eval_df_reg[eval_df_reg["y_true"] > 0],
    "4. Extreme Events (y >= 984.44)": eval_df_reg[eval_df_reg["y_true"] >= PERCENTILE_90_THRESHOLD]
}

print("\n" + "="*75)
print("9.1.2 REGRESSION DIAGNOSTICS - SUBSET EVALUATION")
print("="*75)

results = []
for name, subset in subsets.items():
    if len(subset) > 0:
        rmse = np.sqrt(mean_squared_error(subset["y_true"], subset["y_pred"]))
        mae = mean_absolute_error(subset["y_true"], subset["y_pred"])
        results.append({
            "Data Subset": name,
            "N (Count)": len(subset),
            "RMSE": round(rmse, 2),
            "MAE": round(mae, 2)
        })

print(pd.DataFrame(results).to_string(index=False))